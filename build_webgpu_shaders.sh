#!/bin/bash
# Embeds the WGSL shaders (shaders/webgpu/*.wgsl) into src/shaders/webgpu_default.h.
# WGSL is compiled by the browser, so there's no compiler step; validate and
# render-check the shaders with test/webgpu/run_wgsl_check.sh.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
python3 - "$SCRIPT_DIR/shaders/webgpu/default.wgsl" "$SCRIPT_DIR/shaders/webgpu/ssao.wgsl" "$SCRIPT_DIR/shaders/webgpu/sky.wgsl" "$SCRIPT_DIR/shaders/webgpu/ibl_bake.wgsl" "$SCRIPT_DIR/shaders/webgpu/copy.wgsl" "$SCRIPT_DIR/src/shaders/webgpu_default.h" <<'PYEOF'
import sys
src, ssao_src, sky_src, bake_src, copy_src, out = sys.argv[1:7]
text = open(src).read()
ssao = open(ssao_src).read()
sky = open(sky_src).read()
bake = open(bake_src).read()
copy = open(copy_src).read()
assert all(')WGSL"' not in t for t in (text, ssao, sky, bake, copy))
open(out, 'w').write(
    "// Generated by build_webgpu_shaders.sh from shaders/webgpu/*.wgsl. Do not edit.\n"
    "#pragma once\n\n"
    "namespace systems::leal::campello_renderer::shaders {\n\n"
    "// Built-in PBR mesh shaders (WGSL): vs_main, vs_lean, vs_line, fs_main.\n"
    "static const char kDefaultWebGpuShader[] = R\"WGSL(" + text + ")WGSL\";\n\n"
    "// Screen-space ambient occlusion (WGSL): vs_fullscreen, fs_ssao, fs_ssao_apply.\n"
    "static const char kSsaoWebGpuShader[] = R\"WGSL(" + ssao + ")WGSL\";\n\n"
    "// Sky (WGSL): vs_sky_fullscreen, fs_skybox.\n"
    "static const char kSkyWebGpuShader[] = R\"WGSL(" + sky + ")WGSL\";\n\n"
    "// Image-based lighting precompute (WGSL): vs_sky_fullscreen, fs_ibl_bake.\n"
    "static const char kIblBakeWebGpuShader[] = R\"WGSL(" + bake + ")WGSL\";\n\n"
    "// Copy / SSAA downsample (WGSL): vs_copy, fs_copy.\n"
    "static const char kCopyWebGpuShader[] = R\"WGSL(" + copy + ")WGSL\";\n\n"
    "} // namespace systems::leal::campello_renderer::shaders\n")
print("Embedded:", src, "->", out)
PYEOF
